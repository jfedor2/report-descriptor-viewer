#define TABLE(t) t, sizeof(t) / sizeof(t[0])

static const char* lookup(const Name* table, size_t count, uint16_t id) {
    for (size_t i = 0; i < count; i++) {
        if (table[i].id == id) {
            return table[i].name;
        }
    }
    return nullptr;
}

std::string usage_page_name(uint16_t page) {
    if (const char* name = lookup(TABLE(PAGES), page)) {
        return name;
    }
    char buf[48];
    if (page >= 0xFF00) {
        snprintf(buf, sizeof(buf), "Vendor Defined 0x%04X", page);
    } else {
        snprintf(buf, sizeof(buf), "0x%02X", page);
    }
    return buf;
}

std::string usage_name(uint16_t page, uint16_t usage) {
    char buf[48];
    const char* name = nullptr;
    switch (page) {
        case 0x01:
            name = lookup(TABLE(GENERIC_DESKTOP), usage);
            break;
        case 0x02:
            name = lookup(TABLE(SIMULATION), usage);
            break;
        case 0x05:
            name = lookup(TABLE(GAME_CONTROLS), usage);
            break;
        case 0x06:
            name = lookup(TABLE(GENERIC_DEVICE), usage);
            break;
        case 0x07:
            if (usage >= 0x04 && usage <= 0x1D) {
                snprintf(buf, sizeof(buf), "Keyboard %c", 'A' + usage - 0x04);
                return buf;
            }
            if (usage >= 0x1E && usage <= 0x27) {
                snprintf(buf, sizeof(buf), "Keyboard %c", usage == 0x27 ? '0' : '1' + usage - 0x1E);
                return buf;
            }
            if (usage >= 0x3A && usage <= 0x45) {
                snprintf(buf, sizeof(buf), "Keyboard F%d", usage - 0x3A + 1);
                return buf;
            }
            if (usage >= 0x68 && usage <= 0x73) {
                snprintf(buf, sizeof(buf), "Keyboard F%d", usage - 0x68 + 13);
                return buf;
            }
            if (usage >= 0x59 && usage <= 0x61) {
                snprintf(buf, sizeof(buf), "Keypad %d", usage - 0x59 + 1);
                return buf;
            }
            if (usage >= 0x87 && usage <= 0x8F) {
                snprintf(buf, sizeof(buf), "Keyboard International%d", usage - 0x87 + 1);
                return buf;
            }
            if (usage >= 0x90 && usage <= 0x98) {
                snprintf(buf, sizeof(buf), "Keyboard LANG%d", usage - 0x90 + 1);
                return buf;
            }
            if ((name = lookup(TABLE(KEYBOARD), usage)) != nullptr && usage >= 0x04) {
                return std::string("Keyboard ") + name;
            }
            break;
        case 0x08:
            name = lookup(TABLE(LED), usage);
            break;
        case 0x09:
            if (usage == 0) {
                return "No Button Pressed";
            }
            snprintf(buf, sizeof(buf), "Button %d", usage);
            return buf;
        case 0x0A:
            snprintf(buf, sizeof(buf), "Instance %d", usage);
            return buf;
        case 0x0B:
            name = lookup(TABLE(TELEPHONY), usage);
            break;
        case 0x0C:
            name = lookup(TABLE(CONSUMER), usage);
            break;
        case 0x0D:
            name = lookup(TABLE(DIGITIZERS), usage);
            break;
        case 0xF1D0:
            name = lookup(TABLE(FIDO), usage);
            break;
    }
    return name ? name : std::string();
}
